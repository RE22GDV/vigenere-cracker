def builtin_corpus() -> str:
    """Corpus plus word list; words are useful n-gram material too."""
    return CORPUS + "\n" + WORDS


def builtin_words() -> list:
    seen = {}
    for w in WORDS.split():
        w = w.strip().lower()
        if len(w) >= 2 and all('а' <= c <= 'я' or c == 'ё' for c in w):
            seen[w] = True
    return list(seen)

